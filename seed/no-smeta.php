<?php
/**
 * Цена — фиксированная за м² по тарифу, без сметы: правит тексты, сохранённые в базе
 * (частые вопросы, «О компании», услуги). Повторный запуск ничего не меняет.
 *
 * Отдельный запуск: docker compose run --rm wpcli wp eval-file /seed/no-smeta.php
 */

defined( 'ABSPATH' ) || exit;

$rmt_faq = array(
	'Сколько стоит ремонт квартиры?'                 => array( 'Сколько стоит ремонт?', 'Стоимость работ считается от площади по тарифу: «Эконом», «Стандарт» или «Премиум». Калькулятор на сайте сразу показывает окончательную цену работ под ключ, материалы оплачиваются отдельно. Цена фиксируется в договоре.' ),
	'Может ли стоимость измениться во время ремонта?' => array( 'Может ли стоимость измениться во время ремонта?', 'Нет. Стоимость работ зависит только от площади и тарифа и фиксируется в договоре. Если вы захотите добавить работы, которые не входят в тариф, мы сначала согласуем их и цену письменно и только потом выполняем.' ),
	'Кто закупает материалы?'                         => array( 'Кто закупает материалы?', 'Можно доверить закупку нам — материалы привезут к нужному этапу. Можно закупать самостоятельно по нашему списку. Стоимость материалов в цену работ не входит и оплачивается отдельно.' ),
);
foreach ( $rmt_faq as $rmt_old => list( $rmt_title, $rmt_answer ) ) {
	$rmt_found = get_posts( array( 'post_type' => 'faq', 'title' => $rmt_old, 'numberposts' => 1, 'post_status' => 'any' ) );
	if ( $rmt_found && false !== mb_strpos( $rmt_found[0]->post_content, 'смет' ) ) {
		wp_update_post( wp_slash( array( 'ID' => $rmt_found[0]->ID, 'post_title' => $rmt_title, 'post_content' => $rmt_answer ) ) );
		WP_CLI::log( "Вопрос: {$rmt_title}" );
	}
}

$rmt_replace = array(
	'подробная смета до начала работ'                => 'фиксированная цена за м² до начала работ',
	'Затем — смета и договор с графиком.'             => 'Затем — договор с фиксированной ценой и графиком.',
	'Замер и подробная смета'                         => 'Замер и договор с фиксированной ценой',
	'Смета и график работ'                            => 'Договор с ценой и графиком работ',
	'Предварительную стоимость покажет калькулятор. Точную сумму фиксируем в смете после замера.' => 'Стоимость работ считается от площади по тарифу — её сразу покажет калькулятор. После замера фиксируем цену в договоре.',
	'Предварительную стоимость покажет калькулятор. Точную сумму фиксируем в смете после выезда на объект.' => 'Стоимость работ считается от площади по тарифу — её сразу покажет калькулятор. После выезда на объект фиксируем цену в договоре.',
);
$rmt_targets = array( array( 'page', 'o-kompanii' ), array( 'service', 'remont-kvartir' ), array( 'service', 'remont-domov' ) );
foreach ( $rmt_targets as list( $rmt_type, $rmt_slug ) ) {
	$rmt_post = get_page_by_path( $rmt_slug, OBJECT, $rmt_type );
	if ( ! $rmt_post ) {
		continue;
	}
	$rmt_content = strtr( $rmt_post->post_content, $rmt_replace );
	if ( $rmt_content !== $rmt_post->post_content ) {
		wp_update_post( wp_slash( array( 'ID' => $rmt_post->ID, 'post_content' => $rmt_content ) ) );
		WP_CLI::log( "Текст: {$rmt_slug}" );
	}
	$rmt_inc = (string) get_post_meta( $rmt_post->ID, '_rmt_includes', true );
	if ( $rmt_inc && strtr( $rmt_inc, $rmt_replace ) !== $rmt_inc ) {
		update_post_meta( $rmt_post->ID, '_rmt_includes', strtr( $rmt_inc, $rmt_replace ) );
		WP_CLI::log( "Что входит: {$rmt_slug}" );
	}
}

WP_CLI::success( 'Тексты без сметы: цена — фиксированная за м² по тарифу.' );
